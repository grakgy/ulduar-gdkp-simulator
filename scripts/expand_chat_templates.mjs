const rows = parseCsv(await fs.readFile('Chat_Templates.csv', 'utf8'))
const seen = new Set(rows.map((row) => `${row.scene}\u0000${row.style_or_trait}\u0000${row.template}`))

for (const [scene, styles] of Object.entries(phraseBanks)) {
  for (const [style, [starts, ends]] of Object.entries(styles)) {
    const existing = () => rows.filter((row) => row.scene === scene && row.style_or_trait === style).length
    for (const start of starts) {
      for (const end of ends) {
        if (existing() >= 15) break
        const template = `${start}${end}`.replace(/\s+/g, ' ').trim()
        const key = `${scene}\u0000${style}\u0000${template}`
        if (seen.has(key)) continue
        rows.push({ scene, style_or_trait: style, template })
        seen.add(key)
      }
      if (existing() >= 15) break
    }
    if (existing() < 15) throw new Error(`${scene}/${style} only has ${existing()} templates`)
  }
}

const output = [
  'scene,style_or_trait,template',
  ...rows.map((row) => [row.scene, row.style_or_trait, row.template].map(csvCell).join(',')),
]
await fs.writeFile('Chat_Templates.csv', `${output.join('\r\n')}\r\n`, 'utf8')

const counts = {}
for (const row of rows) {
  counts[row.scene] ??= {}
  counts[row.scene][row.style_or_trait] = (counts[row.scene][row.style_or_trait] ?? 0) + 1
}
